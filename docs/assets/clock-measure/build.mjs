head += slab({ x: -2, y: -8, w: 4, d: 36, r: 0.8 }, 12, 4, "hi");
for (const y of [-3, 12]) head += S(k.slabOf({ x: -1.3, y: y - 1.3, w: 2.6, d: 2.6, r: 0.4 }, 6, 6, P, 3, 0.3), { tone: "hi", lit: true });
