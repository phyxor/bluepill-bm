el('theme').addEventListener('click', () => {
  const dark = document.body.dataset.theme !== 'dark';
  document.body.dataset.theme = dark ? 'dark' : 'light';
  el('theme').setAttribute('aria-label', 'Switch to ' + (dark ? 'light' : 'dark') + ' theme');
});
